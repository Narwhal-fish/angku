"""Synthetic N-D "blob" segmentation data, for smoke tests and CI.

Each sample is a volume with one solid sphere of a random class on a noisy
background; the target is the class mask. Fully deterministic given ``seed``,
so two runs of the same spec see identical data.
"""

from __future__ import annotations

from typing import Any

import torch
from torch import Tensor
from torch.utils.data import TensorDataset

from angku.domain.experiment import Dataset
from angku.domain.split import SplitAssignment
from angku.ports.data import DataError, DataSplits


class SyntheticBlobs:
    """Serves exactly one dataset name (default ``synthetic-blobs``)."""

    def __init__(
        self,
        *,
        n_train: int = 8,
        n_val: int = 4,
        shape: tuple[int, ...] = (8, 8, 8),
        in_channels: int = 1,
        num_classes: int = 2,
        seed: int = 0,
        name: str = "synthetic-blobs",
    ) -> None:
        if num_classes < 2:
            raise ValueError("num_classes must be >= 2 (background + at least one blob class)")
        self.n_train = n_train
        self.n_val = n_val
        self.shape = tuple(shape)
        self.in_channels = in_channels
        self.num_classes = num_classes
        self.seed = seed
        self.name = name

    def snapshot(self, dataset: Dataset) -> None:
        # Generated by code, not stored: code.commit pins it, there are no bytes to hash.
        return None

    def cases(self, dataset: Dataset) -> list[str]:
        """``case-000`` ... one per generated sample (``n_train + n_val`` of them). Without
        ``spec.split`` the first ``n_train`` are train and the rest val."""
        self._check(dataset)
        return [f"case-{i:03d}" for i in range(self.n_train + self.n_val)]

    def load(self, dataset: Dataset, preprocessing: dict[str, Any], split: SplitAssignment | None = None) -> DataSplits:
        self._check(dataset)
        if preprocessing:
            raise DataError(f"SyntheticBlobs has no preprocessing options, got {sorted(preprocessing)}")
        g = torch.Generator().manual_seed(self.seed)
        if split is None:
            train = self._make(self.n_train, g)
            val = self._make(self.n_val, g) if self.n_val else None
            return DataSplits(train=train, val=val)
        # The same samples, in the same generation order; only who goes where changes.
        pool = self._make(self.n_train + self.n_val, g)
        index = {c: i for i, c in enumerate(self.cases(dataset))}

        def part(ids: list[str]) -> TensorDataset | None:
            unknown = [c for c in ids if c not in index]
            if unknown:
                raise DataError(f"SyntheticBlobs has no case(s) {', '.join(unknown[:5])}")
            if not ids:
                return None
            rows = torch.tensor([index[c] for c in ids])
            return TensorDataset(*(t[rows] for t in pool.tensors))

        train = part(split.train)
        assert train is not None  # assign_split never returns an empty train
        return DataSplits(train=train, val=part(split.val), test=part(split.test))

    def _check(self, dataset: Dataset) -> None:
        if dataset.name != self.name:
            raise DataError(f"SyntheticBlobs serves {self.name!r}, not {dataset.name!r}")

    def _make(self, n: int, g: torch.Generator) -> TensorDataset:
        xs: list[Tensor] = []
        ys: list[Tensor] = []
        grids = torch.meshgrid(*[torch.arange(s, dtype=torch.float32) for s in self.shape], indexing="ij")
        for _ in range(n):
            cls = int(torch.randint(1, self.num_classes, (1,), generator=g))
            center = [float(torch.randint(0, s, (1,), generator=g)) for s in self.shape]
            radius = min(self.shape) / 4
            dist2 = sum((grid - c) ** 2 for grid, c in zip(grids, center, strict=True))
            mask = dist2 <= radius**2
            y = torch.where(mask, torch.tensor(cls), torch.tensor(0)).long()
            x = mask.float().unsqueeze(0).repeat(self.in_channels, *([1] * len(self.shape)))
            x = x + 0.1 * torch.randn(x.shape, generator=g)
            xs.append(x)
            ys.append(y)
        return TensorDataset(torch.stack(xs), torch.stack(ys))
